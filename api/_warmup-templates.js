/**
 * Generates a unique warmup email by combining random segments.
 * 100 × 100 × 100 × 100 = 100,000,000 unique email body combinations.
 * 100 unique subjects. 100 unique replies.
 */
export function generateEmail() {
  const subject = pick(subjects);
  const opener = pick(openers);
  const body = pick(bodies);
  const closer = pick(closers);
  const reply = pick(replies);

  return {
    subject,
    body: `${opener}\n\n${body}\n\n${closer}`,
    reply,
  };
}

function pick(arr) {
  return arr[Math.floor(Math.random() * arr.length)];
}
